"""Caption writers: ASS (styled, word-animated), SRT, WebVTT (with word timestamps), JSON."""

from __future__ import annotations

import json
import re
from typing import Any

from reelferry.captions.layout import CaptionWord, Page
from reelferry.captions.styles import CaptionStyle

CAPTION_FORMATS = ("srt", "vtt", "ass", "json")


def _srt_time(seconds: float) -> str:
    ms = max(0, round(seconds * 1000))
    h, rest = divmod(ms, 3_600_000)
    m, rest = divmod(rest, 60_000)
    s, ms = divmod(rest, 1000)
    return f"{h:02d}:{m:02d}:{s:02d},{ms:03d}"


def _vtt_time(seconds: float) -> str:
    return _srt_time(seconds).replace(",", ".")


def _ass_time(seconds: float) -> str:
    cs = max(0, round(seconds * 100))
    h, rest = divmod(cs, 360_000)
    m, rest = divmod(rest, 6000)
    s, cs = divmod(rest, 100)
    return f"{h:d}:{m:02d}:{s:02d}.{cs:02d}"


def to_srt(pages: list[Page]) -> str:
    blocks = [
        f"{index}\n{_srt_time(page.start)} --> {_srt_time(page.end)}\n{page.text}\n"
        for index, page in enumerate(pages, start=1)
    ]
    return "\n".join(blocks)


def to_vtt(pages: list[Page]) -> str:
    """WebVTT with inline word timestamps, so players can highlight word by word."""
    out = ["WEBVTT", ""]
    for page in pages:
        out.append(f"{_vtt_time(page.start)} --> {_vtt_time(page.end)}")
        rendered_lines = []
        first = True
        for line in page.lines:
            tokens = []
            for word in line:
                if first:
                    tokens.append(word.text)
                    first = False
                else:
                    tokens.append(f"<{_vtt_time(word.start)}>{word.text}")
            rendered_lines.append(" ".join(tokens))
        out.append("\n".join(rendered_lines))
        out.append("")
    return "\n".join(out)


def to_json(pages: list[Page], words: list[CaptionWord]) -> str:
    payload: dict[str, Any] = {
        "words": [
            {"text": w.text, "start": w.start, "end": w.end, "emphasis": w.emphasis} for w in words
        ],
        "pages": [
            {
                "start": page.start,
                "end": page.end,
                "lines": [[w.text for w in line] for line in page.lines],
            }
            for page in pages
        ],
    }
    return json.dumps(payload, ensure_ascii=False, indent=2)


# ASS


def _ass_color(rgb: str, alpha: int = 0) -> str:
    r, g, b = rgb[0:2], rgb[2:4], rgb[4:6]
    return f"&H{alpha:02X}{b}{g}{r}".upper()


def _inline_color(rgb: str) -> str:
    return f"&H{rgb[4:6]}{rgb[2:4]}{rgb[0:2]}&".upper()


def _escape(text: str) -> str:
    return text.replace("\\", "/").replace("{", "(").replace("}", ")")


def font_size(style: CaptionStyle, width: int, height: int) -> int:
    by_height = style.size * height
    # libass sizes fonts by line height; an average glyph is about half that wide.
    by_width = 0.9 * width / (style.max_chars_per_line * 0.5)
    return max(12, round(min(by_height, by_width)))


def to_ass(pages: list[Page], style: CaptionStyle, width: int, height: int) -> str:
    size = font_size(style, width, height)
    portrait = height > width
    outline = round(style.outline * size, 1)
    shadow = round(style.shadow * size, 1)
    if style.position == "middle":
        alignment, margin_v = 5, 0
    elif style.position == "lower_third":
        alignment, margin_v = 2, round(height * (0.24 if portrait else 0.1))
    else:
        alignment, margin_v = 2, round(height * (0.12 if portrait else 0.06))
    margin_h = round(width * 0.06)
    karaoke = style.animation == "karaoke"
    primary = style.active_color if karaoke else style.text_color
    secondary = style.text_color
    header = "\n".join(
        [
            "[Script Info]",
            "; Generated by Reelferry",
            "ScriptType: v4.00+",
            f"PlayResX: {width}",
            f"PlayResY: {height}",
            "WrapStyle: 2",
            "ScaledBorderAndShadow: yes",
            "YCbCr Matrix: TV.709",
            "",
            "[V4+ Styles]",
            "Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour,"
            " BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle,"
            " BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding",
            "Style: Default,{font},{size},{primary},{secondary},{outline_c},{back},{bold},0,0,0,"
            "100,100,{spacing},0,1,{outline},{shadow},{alignment},{mh},{mh},{mv},1".format(
                font=style.font,
                size=size,
                primary=_ass_color(primary),
                secondary=_ass_color(secondary),
                outline_c=_ass_color(style.outline_color),
                back=_ass_color("000000", 0x80),
                bold=-1 if style.bold else 0,
                spacing=style.letter_spacing,
                outline=outline,
                shadow=shadow,
                alignment=alignment,
                mh=margin_h,
                mv=margin_v,
            ),
            "",
            "[Events]",
            "Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text",
        ]
    )
    events: list[str] = []
    for page in pages:
        if karaoke:
            events.append(_dialogue(page.start, page.end, _karaoke_text(page, style)))
        elif style.animation == "none":
            events.append(_dialogue(page.start, page.end, _page_text(page, style, None, size)))
        else:
            words = page.words
            for index, word in enumerate(words):
                start = page.start if index == 0 else word.start
                end = words[index + 1].start if index + 1 < len(words) else page.end
                if end - start < 0.01:
                    continue
                text = _page_text(page, style, word, size)
                if style.animation == "glow":
                    events.append(_dialogue(start, end, _glow_layer(text, style, size), layer=0))
                    events.append(_dialogue(start, end, text, layer=1))
                else:
                    events.append(_dialogue(start, end, text))
    return header + "\n" + "\n".join(events) + "\n"


def _dialogue(start: float, end: float, text: str, *, layer: int = 0) -> str:
    return f"Dialogue: {layer},{_ass_time(start)},{_ass_time(end)},Default,,0,0,0,,{text}"


def _glow_layer(text: str, style: CaptionStyle, size: int) -> str:
    """The same line as a soft colored halo behind the text (fill hidden, wide blurred border)."""
    bord = round(size * 0.16, 1)
    blur = round(size * 0.14, 1)
    halo = (
        f"{{\\1a&HFF&\\3c{_inline_color(style.outline_color)}\\3a&H30&"
        f"\\bord{bord}\\blur{blur}\\shad0}}"
    )
    # Inline overrides in the text layer would undo the halo; keep only the words.
    plain = re.sub(r"{[^}]*}", "", text)
    return halo + plain


def _display(word: CaptionWord, style: CaptionStyle) -> str:
    text = word.text.upper() if style.uppercase else word.text
    return _escape(text)


def _page_text(page: Page, style: CaptionStyle, active: CaptionWord | None, size: int) -> str:
    prefix = "{\\blur1}" if style.animation == "glow" else ""
    rendered_lines: list[str] = []
    for line in page.lines:
        tokens: list[str] = []
        for word in line:
            text = _display(word, style)
            if word is active:
                tokens.append(_active(text, style, size))
            elif word.emphasis and style.emphasis_color != style.text_color:
                tokens.append(f"{{\\c{_inline_color(style.emphasis_color)}}}{text}{{\\r}}")
            else:
                tokens.append(text)
        rendered_lines.append(" ".join(tokens))
    return prefix + "\\N".join(rendered_lines)


def _active(text: str, style: CaptionStyle, size: int) -> str:
    color = _inline_color(style.active_color)
    if style.animation == "pop":
        return f"{{\\c{color}\\fscx114\\fscy114\\t(0,100,\\fscx104\\fscy104)}}{text}{{\\r}}"
    if style.animation == "box":
        pad = round(size * 0.22)
        box = _inline_color(style.box_color)
        return f"{{\\c{color}\\3c{box}\\bord{pad}\\shad0\\blur0}}{text}{{\\r}}"
    if style.animation == "glow":
        return f"{{\\c{color}\\fscx106\\fscy106}}{text}{{\\r\\blur1}}"
    return text


def _karaoke_text(page: Page, style: CaptionStyle) -> str:
    rendered_lines: list[str] = []
    cursor = page.start
    for line in page.lines:
        tokens: list[str] = []
        for word in line:
            lead = max(0, round((word.start - cursor) * 100))
            dur = max(1, round((word.end - word.start) * 100))
            text = _display(word, style)
            if word.emphasis and style.emphasis_color != style.text_color:
                emph = _inline_color(style.emphasis_color)
                text = f"{{\\2c{emph}}}{text}{{\\2c{_inline_color(style.text_color)}}}"
            gap = f"{{\\k{lead}}}" if lead else ""
            tokens.append(f"{gap}{{\\kf{dur}}}{text}")
            cursor = word.end
        rendered_lines.append(" ".join(tokens))
    return "\\N".join(rendered_lines)
